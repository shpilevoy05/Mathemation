def load_theory_bank(*, dry_run: bool = False) -> dict:
    """Разложить банк по базе. Идемпотентно: ключ — тема и текст вопроса.

    Кластеров может не быть (пустая база) — такие темы пропускаются молча:
    банк описывает предметную область, а не гарантирует состав справочника.
    """
    from apps.knowledge.models import TopicCluster

    from .models import TheoryQuestion

    created = updated = skipped = 0
    for title, rows in BANK.items():
        cluster = TopicCluster.objects.filter(title=title).first()
        if cluster is None:
            skipped += len(rows)
            continue
        for difficulty, prompt, answer_format, correct, accepted, options, hint in rows:
            fields = {
                "answer_format": answer_format,
                "correct_answer": correct,
                "accepted_answers": list(accepted),
                "options": list(options),
                "format_hint": hint,
                "difficulty": difficulty,
                "is_active": True,
            }
            if dry_run:
                exists = TheoryQuestion.objects.filter(
                    cluster=cluster, prompt=prompt
                ).exists()
                updated += 1 if exists else 0
                created += 0 if exists else 1
                continue
            _, was_created = TheoryQuestion.objects.update_or_create(
                cluster=cluster, prompt=prompt, defaults=fields
            )
            created += int(was_created)
            updated += int(not was_created)
    return {"created": created, "updated": updated, "skipped": skipped}
