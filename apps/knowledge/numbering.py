"""Перенумерация заданий ЕГЭ при смене структуры экзамена.

Номер задания — это не свойство навыка, а место навыка в конкретной версии
экзамена. Когда структура меняется, номера в графе нужно перевести целиком:
иначе прогноз считает по старой раскладке, план ведёт к несуществующему
заданию, а «нарешивание прототипа 13» открывает не то, что написано.

Карта ниже переводит нумерацию 19-задачного варианта (до 2027 года) в
20-задачный. Она не обратима: прежние задания 8 (производная по графику) и 12
(наибольшее и наименьшее значение) сведены в новое задание 9, поэтому откатить
перевод автоматически нельзя.
"""

from __future__ import annotations

# старый номер → новый номер
EGE_2027_RENUMBERING: dict[int, int] = {
    1: 1,    # планиметрия
    2: 2,    # векторы
    3: 3,    # стереометрия
    4: 4,    # вероятность события
    5: 5,    # сложная вероятность
    # 6 — новое задание про случайные величины, прежнего номера у него нет
    6: 7,    # простейшие уравнения
    7: 8,    # вычисления и преобразования
    8: 9,    # производная по графику → исследование функций
    9: 10,   # прикладные задачи (моделирование)
    10: 11,  # текстовые задачи
    11: 12,  # графики функций и зависимости
    12: 9,   # наибольшее и наименьшее значение — тоже в задание 9
    # 13 — новое задание про личные и семейные финансы
    13: 14,  # уравнение части 2
    14: 15,  # стереометрия части 2
    15: 16,  # неравенство
    16: 17,  # экономическая задача
    17: 18,  # планиметрия части 2
    18: 19,  # параметр
    19: 20,  # числа и их свойства
}

# Задания, которых в прежней структуре не было: их закрывают новые навыки, а не
# перенумерация. Список нужен отчётам, чтобы дыра в графе была видна сразу.
NEW_IN_2027 = [6, 13]


def renumber(numbers, mapping: dict[int, int] | None = None) -> list[int]:
    """Перевести список номеров заданий в новую нумерацию.

    Порядок сохраняется, повторы убираются: после слияния заданий 8 и 12 узел
    может получить один и тот же номер дважды.
    """
    mapping = mapping if mapping is not None else EGE_2027_RENUMBERING
    result: list[int] = []
    for value in numbers or []:
        try:
            number = int(value)
        except (TypeError, ValueError):
            continue
        moved = mapping.get(number, number)
        if moved not in result:
            result.append(moved)
    return result


def renumber_nodes(node_model, mapping: dict[int, int] | None = None) -> int:
    """Перевести номера у всех узлов графа. Возвращает число изменённых узлов."""
    changed = 0
    for node in node_model.objects.exclude(ege_task_numbers=[]).only(
        "id", "ege_task_numbers"
    ):
        moved = renumber(node.ege_task_numbers, mapping)
        if moved != list(node.ege_task_numbers or []):
            node_model.objects.filter(pk=node.pk).update(ege_task_numbers=moved)
            changed += 1
    return changed
